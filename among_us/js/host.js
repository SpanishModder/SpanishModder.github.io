  /* Empuja a un jugador fuera de los muros. Sirve para muros rectos, diagonales e inclinados,
    y hace que se deslice por ellos en vez de quedarse pegado. */
  function collide(p) {
    for (let i = 0; i < 4; i++) {
      let hit = false;

      for (const w of WALLS) {
        const ex = w.x2 - w.x1, ey = w.y2 - w.y1, l2 = ex * ex + ey * ey;
        const px = p.x;
        const py = p.y + coy;

        const u = l2
          ? clamp(((px - w.x1) * ex + (py - w.y1) * ey) / l2, 0, 1)
          : 0;

        const cx = w.x1 + ex * u;
        const cy = w.y1 + ey * u;
        const min = PR + w.t / 2;

        let dx = px - cx;
        let dy = py - cy;
        let d = Math.hypot(dx, dy);

        if (d >= min) continue;

        if (d < 1e-6) { // justo encima del muro: sacar por su normal
          const l = Math.sqrt(l2) || 1;
          dx = -ey / l; dy = ex / l; d = 1;
        }

        p.x = cx + dx / d * min;
        p.y = cy + dy / d * min - coy;
        hit = true;
      }

      if (!hit) break;
    }
  }

